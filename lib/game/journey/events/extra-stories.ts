export function extraStories(life: Life, healthOnly = false): StoryEvent[] {
  return extraStoryDefinitions
    .filter(
      (row) =>
        life.age >= row[3] &&
        life.age <= row[4] &&
        (!healthOnly || row[6] === "สุขภาพ") &&
        (row[0] !== "relocation" || !!life.journey!.career),
    )
    .map(([id, title, text, min, max, skill, category, labels]) => {
      const health = category === "สุขภาพ",
        fee = health ? 2000 : min < 18 ? 300 : 1500;
      return event(
        life,
        id + "-" + life.age,
        title,
        text,
        [
          option(
            labels[0],
            health ? "พักดูแลตัวเอง · สุขภาพ +6" : "ใช้ทักษะ · สำเร็จทักษะเฉพาะ +8",
            health ? { stats: { health: 6 } } : { skills: { [skill]: 8 } },
            {
              icon: health ? "heart" : "book",
              ...(health
                ? {}
                : {
                    chance: { base: 55, skill: skill as Skill },
                    failure: { skills: { [skill]: 2 }, stats: { happy: -2 } },
                  }),
            },
          ),
          option(
            labels[1],
            "ค่าใช้จ่าย " + fee + " · " + (health ? "สุขภาพ +12" : "ทักษะเฉพาะ +10"),
            health ? { stats: { health: 12 } } : { skills: { [skill]: 10 } },
            { icon: health ? "heart" : "tool", cost: fee },
          ),
          option(
            labels[2],
            health ? "สุขภาพ +5 · สัมพันธ์ +4" : "สัมพันธ์ +7 · ทักษะเฉพาะ +3",
            health
              ? { stats: { health: 5, social: 4 } }
              : { stats: { social: 7 }, skills: { [skill]: 3 } },
            { icon: "users" },
          ),
          option(
            labels[3],
            health ? "สุขภาพ +8 · ไม่เสียเงิน" : "วิชาการ +4 · ทักษะเฉพาะ +5",
            health ? { stats: { health: 8 } } : { skills: { academic: 4, [skill]: 5 } },
            { icon: "book" },
          ),
          option(
            labels[4],
            health ? "สุขภาพ -10 · ความสุข -3" : "ไม่เสียเงิน · สุขภาพ +2 · ความสุข +3",
            health
              ? { stats: { health: -10, happy: -3 } }
              : { stats: { health: 2, happy: 3 } },
            { icon: health ? "danger" : "moon" },
          ),
        ],
        category,
        health
          ? "hospital"
          : category === "โรงเรียน" || category === "การศึกษา"
            ? "home"
            : "festival",
      );
    });
}
