export function positionTitle(id: string, rank: number) {
  return careerPaths[id]?.titles[Math.min(rank, 3)] || "ผู้ชำนาญงาน";
}
export function careerMission(life: Life) {
  const c = life.journey!.career;
  if (!c) return null;
  const job = jobs.find((j) => j.id === c.id)!;
  return {
    id: c.id,
    title: careerPaths[c.id].mission,
    value: life.journey!.skills[job.skill],
    rank: c.rank,
  };
}
export function settleMission(life: Life) {
  const mission = careerMission(life);
  if (
    !mission ||
    mission.value < 70 ||
    mission.rank < 1 ||
    life.journey!.completedMissions.includes(mission.id)
  )
    return;
  life.journey!.completedMissions.push(mission.id);
  life.stats.happy = Math.min(100, life.stats.happy + 10);
  life.journey!.queue.push({
    id: "mission-" + mission.id,
    title: "ภารกิจอาชีพสำเร็จ!",
    text: mission.title,
    scene: "festival",
    effects: "ความสุข +10 · ได้ตราความสำเร็จถาวร",
  });
}
